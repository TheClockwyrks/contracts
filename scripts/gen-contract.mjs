// Generate the data contract and the backend's API package, their TypeScript
// bindings and their JSON Schemas, from the Rust types that are their single
// source of truth.
//
// The work happens in four steps. `contract-codegen` (`crates/contract-codegen`)
// emits the data contract's TypeScript (`packages/run-record/src/`,
// `packages/asset-contract/src/`) and JSON Schemas (`schema/core/`, `schema/gg/`),
// and `api-codegen` (`crates/api-codegen`) emits the backend API's
// (`packages/backend-api/src/`, and `schema/backend-api/`, `schema/coverage/`,
// `schema/jobs-api/` and `schema/snapshot/`), both from `crates/contracts`, whose
// types derive `ts_rs::TS` + `schemars::JsonSchema` behind its `contract` feature.
// The second step mirrors gg's built-in system-prompt templates into the backend
// API package. The generators are correct but not pretty (ts_rs emits ragged
// whitespace), so the third step runs Prettier to make the committed output
// deterministic and conventional. The `contract-drift` gate regenerates and fails
// on any diff (`scripts/ci/contract-drift.sh`), so the committed artifacts always
// match the Rust source and hand edits never survive. The last step compiles the
// regenerated TypeScript, because `dist/`, not `src/`, is what every consumer of
// the packages imports.
//
// Usage: `npm run gen:contract` (from the repository root).

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

function run(cmd, args) {
  execFileSync(cmd, args, { stdio: "inherit" });
}

// 1. Emit raw TS + JSON from the Rust source of truth. `api-codegen` reads the
//    data contract's modules and documents without writing them, so the order
//    between the two does not matter.
run("cargo", ["run", "--quiet", "-p", "contract-codegen"]);
run("cargo", ["run", "--quiet", "-p", "api-codegen"]);

// 2. Mirror gg's built-in system-prompt templates into the backend API package
//    (not the data contract, which depends on nothing of gg's), so the console can
//    seed its per-agent "System Prompt" editor with the exact default an agent's
//    `systemPromptTemplate` override starts from. There are two, chosen by the
//    agent's execution mode: the tool-calling arm names each capability's
//    free-standing tools, and the responses-as-code arm teaches the code protocol.
//    Both are language-agnostic, so there is exactly one file to mirror per mode.
//    The `.hbs` files are the single source of truth (gg embeds them through
//    `test_cabinet_contracts::gg_system_prompt`); this keeps the TS copy from
//    drifting, and the drift gate and that module's test enforce it.
{
  const TEMPLATES = "crates/contracts/templates/gg";
  const tools = readFileSync(`${TEMPLATES}/system-tools.hbs`, "utf8");
  const code = readFileSync(`${TEMPLATES}/system-code.hbs`, "utf8");
  writeFileSync(
    "packages/backend-api/src/gg-system-prompt.ts",
    `// AUTO-GENERATED by scripts/gen-contract.mjs from ${TEMPLATES}/system-tools.hbs\n` +
      `// and ${TEMPLATES}/system-code.hbs.\n` +
      "// DO NOT EDIT BY HAND — edit the .hbs templates and run `npm run gen:contract`.\n\n" +
      "/**\n" +
      " * gg's built-in **tool-calling** system-prompt Handlebars template, verbatim — the\n" +
      " * default a tool-calling agent's `systemPromptTemplate` override starts from, and what\n" +
      " * the console seeds its per-agent System Prompt editor with for one. Partials are\n" +
      " * inlined, so it is self-contained; variables/branches are left intact.\n" +
      " */\n" +
      `export const DEFAULT_GG_SYSTEM_PROMPT_TEMPLATE = ${JSON.stringify(tools)};\n\n` +
      "/**\n" +
      " * gg's built-in **responses-as-code** system-prompt Handlebars template, verbatim — the\n" +
      " * default a code agent's `systemPromptTemplate` override starts from, whatever program\n" +
      " * language it writes.\n" +
      " *\n" +
      " * One template serves every language: it names no function, so what a call is spelled\n" +
      " * like is not in it, and the few things a model cannot discover about its own language\n" +
      " * are a segment gg gates while rendering. Self-contained, like its tool-calling sibling.\n" +
      " */\n" +
      `export const DEFAULT_GG_SYSTEM_PROMPT_TEMPLATE_CODE = ${JSON.stringify(code)};\n`,
  );
}

// 3. Normalize formatting so the committed artifacts are deterministic. Prettier
//    is pinned (see the root `package.json`) so the same input always formats the
//    same way, which is what makes the drift check trustworthy. Every file listed
//    here is one the drift check diffs, and that is the rule: an artifact it guards
//    has to come out of the same formatter, or a byte of whitespace turns CI red.
run("npx", [
  "prettier",
  "--write",
  "--log-level",
  "warn",
  "packages/run-record/src/**/*.ts",
  "packages/asset-contract/src/**/*.ts",
  "packages/backend-api/src/**/*.ts",
  "schema/**/*.json",
]);

// 4. Compile the TypeScript that was just regenerated. Each package's `exports`
//    map points at `dist/`, so emitting only the source leaves every consumer
//    building against the previous contract until something happens to compile
//    it. Regenerating and compiling are one act; do not split them. backend-api
//    references run-record, which references asset-contract, so this builds all
//    three.
run("npx", ["tsc", "-b", "packages/backend-api"]);
